_PAGE_W, _PAGE_H, _MARGIN = 595, 842, 56
_BODY, _HEAD, _LEAD = 10.5, 14.0, 15.0
_WRAP = 86


def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _layout(text: str) -> list[list[tuple[str, float, str]]]:
    """Pages of (font, size, text) lines: the body wrapped, headings set apart."""
    pages: list[list[tuple[str, float, str]]] = [[]]
    y = _PAGE_H - _MARGIN

    def put(font: str, size: float, line: str, gap: float = 0.0) -> None:
        nonlocal y
        need = size + 4 + gap
        if y - need < _MARGIN:
            pages.append([])
            y = _PAGE_H - _MARGIN
        y -= need
        pages[-1].append((font, size, line))

    for raw in text.strip().splitlines():
        line = raw.rstrip()
        if not line:
            continue
        if line.startswith("# "):
            put("F2", _HEAD, line[2:], gap=10.0)
        else:
            for part in textwrap.wrap(line, _WRAP) or [""]:
                put("F1", _BODY, part)
    return pages


def make_pdf(text: str) -> bytes:
    """A small, valid, text-only PDF: Helvetica, one content stream per page."""
    pages = _layout(text)
    objs: list[bytes] = []

    def add(body: bytes) -> int:
        objs.append(body)
        return len(objs)

    cat = add(b"")  # patched below
    pgs = add(b"")
    f1 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    f2 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    kids: list[int] = []
    for lines in pages:
        y = _PAGE_H - _MARGIN
        ops = []
        for font, size, line in lines:
            y -= size + 4 + (10.0 if font == "F2" else 0.0)
            ops.append(f"BT /{font} {size} Tf {_MARGIN} {y:.1f} Td ({_esc(line)}) Tj ET")
        stream = "\n".join(ops).encode("latin-1", "replace")
        content = add(b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream")
        page = add(
            f"<< /Type /Page /Parent {pgs} 0 R /MediaBox [0 0 {_PAGE_W} {_PAGE_H}] "
            f"/Resources << /Font << /F1 {f1} 0 R /F2 {f2} 0 R >> >> /Contents {content} 0 R >>".encode()
        )
        kids.append(page)
    objs[cat - 1] = f"<< /Type /Catalog /Pages {pgs} 0 R >>".encode()
    objs[pgs - 1] = f"<< /Type /Pages /Kids [{' '.join(f'{k} 0 R' for k in kids)}] /Count {len(kids)} >>".encode()

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root {cat} 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def build() -> list[Path]:
    CORPUS.mkdir(exist_ok=True)
    written = []
    for name, text in NOTES.items():
        path = CORPUS / name
        path.write_bytes(make_pdf(text))
        written.append(path)
    return written


if __name__ == "__main__":
    for p in build():
        print("wrote", p.name, p.stat().st_size, "bytes")
